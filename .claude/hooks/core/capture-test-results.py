#!/usr/bin/env python3
# review_by: 2026-09-10
"""
PostToolUse hook to capture and log test results from flutter test runs.

Parses the JSON report file generated by inject-test-reporter.py (via
--file-reporter json:<path>) and appends structured results to
.claude/test-history/test-runs.jsonl.

Follows the pattern from dart-format-post-edit.py - silent on errors, never blocks.
"""
# Hook Contract:
#   Event:        PostToolUse (Bash)
#   Matcher:      tool_name == "Bash" and ("flutter test" or "dart test") in command and --file-reporter present
#   Input:        {"tool_name": "Bash", "tool_input": {"command": "..."}} via stdin
#   Output:       {"hookSpecificOutput": {"hookEventName": "PostToolUse",
#                  "additionalContext": "Test results logged: PASS|FAIL (...)"}}
#   Side effects: Parses --file-reporter JSON report; appends run to test-runs.jsonl;
#                 updates test-cache.py entries for passing tests; rotates old reports
#   Dependencies: test-cache.py (dynamic import), --file-reporter JSON report written by flutter test
import glob
import json
import os
import re
import sys
from datetime import datetime
from pathlib import Path

# Import Context Mode utilities
sys.path.insert(0, str(Path(__file__).resolve().parent))
from context_mode_utils import compress_output

HISTORY_DIR = os.path.join(".claude", "test-history")
REPORTS_DIR = os.path.join(HISTORY_DIR, "reports")
RUNS_FILE = os.path.join(HISTORY_DIR, "test-runs.jsonl")
MAX_REPORTS = 10
MAX_RUNS_FILE_BYTES = 10 * 1024 * 1024  # 10 MB cap
RUNS_TO_KEEP_AFTER_ROTATION = 50


def find_report_path(command):
    """Extract the report path from the flutter test command."""
    match = re.search(r"--file-reporter\s+json:(\S+)", command)
    if match:
        return match.group(1)
    return None


def parse_json_report(report_path):
    """Parse the Dart test JSON reporter output (line-delimited JSON)."""
    suites = {}  # id -> path
    tests = {}  # id -> {name, suiteID}
    errors = {}  # testID -> [error messages]
    results = []
    overall_success = None
    start_time = None
    end_time = None

    try:
        with open(report_path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    event = json.loads(line)
                except json.JSONDecodeError:
                    continue

                event_type = event.get("type", "")
                time_ms = event.get("time", 0)

                if event_type == "start":
                    start_time = time_ms

                elif event_type == "suite":
                    suite = event.get("suite", {})
                    suites[suite.get("id")] = suite.get("path", "unknown")

                elif event_type == "testStart":
                    test = event.get("test", {})
                    tests[test.get("id")] = {
                        "name": test.get("name", "unknown"),
                        "suiteID": test.get("suiteID"),
                    }

                elif event_type == "error":
                    test_id = event.get("testID")
                    if test_id is not None:
                        if test_id not in errors:
                            errors[test_id] = []
                        error_msg = event.get("error", "")
                        # Truncate long error messages
                        if len(error_msg) > 200:
                            error_msg = error_msg[:200] + "..."
                        errors[test_id].append(error_msg)

                elif event_type == "testDone":
                    test_id = event.get("testID")
                    hidden = event.get("hidden", False)
                    if hidden:
                        continue  # Skip hidden/internal test events

                    test_info = tests.get(test_id, {})
                    suite_path = suites.get(test_info.get("suiteID", -1), "unknown")
                    result_entry = {
                        "file": suite_path,
                        "name": test_info.get("name", "unknown"),
                        "result": event.get("result", "unknown"),
                        "skipped": event.get("skipped", False),
                        "duration_ms": time_ms,
                    }
                    # Include error message for failures
                    if test_id in errors:
                        result_entry["error"] = errors[test_id][0]
                    results.append(result_entry)

                elif event_type == "done":
                    overall_success = event.get("success")
                    end_time = time_ms

    except (OSError, UnicodeDecodeError):
        return None

    if not results:
        return None

    # Calculate summary
    passed = sum(1 for r in results if r["result"] == "success" and not r["skipped"])
    failed = sum(1 for r in results if r["result"] == "failure")
    errored = sum(1 for r in results if r["result"] == "error")
    skipped = sum(1 for r in results if r["skipped"])
    total_duration = (end_time - start_time) if (start_time is not None and end_time is not None) else 0

    return {
        "id": f"run-{datetime.now().strftime('%Y-%m-%dT%H-%M-%S')}",
        "timestamp": datetime.now().isoformat(),
        "overall_success": overall_success,
        "total": len(results),
        "passed": passed,
        "failed": failed,
        "errors": errored,
        "skipped": skipped,
        "duration_ms": total_duration,
        "tests": results,
    }


def rotate_reports():
    """Keep only the last MAX_REPORTS JSON report files."""
    try:
        report_files = sorted(glob.glob(os.path.join(REPORTS_DIR, "*.json"))) + sorted(glob.glob(os.path.join(REPORTS_DIR, "*.jsonl")))
        if len(report_files) > MAX_REPORTS:
            for old_file in report_files[:-MAX_REPORTS]:
                try:
                    os.remove(old_file)
                except OSError:
                    pass
    except OSError:
        pass


def rotate_runs_file():
    """Trim test-runs.jsonl to the last N runs when it exceeds the size cap.

    Keeps RUNS_TO_KEEP_AFTER_ROTATION most recent entries. Writes to a temp
    file first and then atomically renames to prevent corruption.
    """
    try:
        file_size = os.path.getsize(RUNS_FILE)
        if file_size <= MAX_RUNS_FILE_BYTES:
            return

        # Read all lines, keep the last N
        with open(RUNS_FILE, "r", encoding="utf-8") as f:
            lines = f.readlines()

        if len(lines) <= RUNS_TO_KEEP_AFTER_ROTATION:
            return  # Few entries but large payloads; nothing to trim

        kept_lines = lines[-RUNS_TO_KEEP_AFTER_ROTATION:]

        # Atomic write: temp file then rename
        tmp_path = RUNS_FILE + ".tmp"
        with open(tmp_path, "w", encoding="utf-8") as f:
            f.writelines(kept_lines)
        os.replace(tmp_path, RUNS_FILE)

    except OSError:
        pass  # Silent on rotation errors


def main():
    try:
        input_data = json.load(sys.stdin)
    except json.JSONDecodeError:
        sys.exit(0)

    tool_name = input_data.get("tool_name", "")
    tool_input = input_data.get("tool_input", {})
    command = tool_input.get("command", "")

    # Only process Bash commands that were test runs (flutter test or dart test)
    if tool_name != "Bash":
        sys.exit(0)
    if "flutter test" not in command and "dart test" not in command:
        sys.exit(0)

    # Find the report file path from the command
    report_path = find_report_path(command)
    if not report_path or not os.path.exists(report_path):
        sys.exit(0)

    # Parse the JSON report
    run_data = parse_json_report(report_path)
    if not run_data:
        sys.exit(0)

    # Add the command to the run data
    run_data["command"] = command

    # Parse coverage data if --coverage flag was in the command
    if "--coverage" in command:
        try:
            from pathlib import Path as _Path
            script_dir = _Path(__file__).resolve().parent
            project_root = script_dir.parent.parent.parent

            # Determine package name from command or cwd
            pkg_name = "unknown"
            # Try to extract package from command path
            for part in command.split():
                if "packages/" in part:
                    pkg_name = part.split("packages/")[1].split("/")[0]
                    break

            # Find lcov.info
            lcov_candidates = [
                project_root / "coverage" / "lcov.info",
            ]
            # Check package-level coverage
            if pkg_name != "unknown":
                lcov_candidates.insert(
                    0, project_root / "packages" / pkg_name / "coverage" / "lcov.info"
                )

            for lcov_path in lcov_candidates:
                if lcov_path.exists():
                    # Parse LCOV inline (SF/DA/end_of_record)
                    lines_hit = 0
                    lines_total = 0
                    generated_patterns = (".g.dart", ".freezed.dart")
                    current_file = None
                    skip_file = False
                    with open(lcov_path, "r") as lf:
                        for lcov_line in lf:
                            lcov_line = lcov_line.strip()
                            if lcov_line.startswith("SF:"):
                                current_file = lcov_line[3:]
                                skip_file = any(
                                    current_file.endswith(p) for p in generated_patterns
                                )
                            elif lcov_line.startswith("DA:") and not skip_file:
                                parts = lcov_line[3:].split(",")
                                if len(parts) >= 2:
                                    lines_total += 1
                                    try:
                                        if int(parts[1]) > 0:
                                            lines_hit += 1
                                    except ValueError:
                                        pass
                            elif lcov_line == "end_of_record":
                                current_file = None
                                skip_file = False

                    if lines_total > 0:
                        pct = round((lines_hit / lines_total) * 100, 2)
                        run_data["coverage"] = {
                            "package": pkg_name,
                            "line_coverage_pct": pct,
                            "lines_hit": lines_hit,
                            "lines_total": lines_total,
                            "threshold": 95,
                            "met": pct >= 95,
                        }
                    break
        except Exception:
            pass  # Silent on coverage parsing errors

    # Determine trigger type
    if ".claude/hooks/smart-test-run.py" in command:
        run_data["trigger"] = "smart"
    elif ".claude/hooks/rerun-failures.py" in command:
        run_data["trigger"] = "rerun"
    else:
        run_data["trigger"] = "manual"

    # Append to JSONL history
    try:
        os.makedirs(HISTORY_DIR, exist_ok=True)
        with open(RUNS_FILE, "a", encoding="utf-8") as f:
            f.write(json.dumps(run_data) + "\n")
    except OSError as e:
        print(f"[capture-test-results] WARNING: could not write test history: {e}",
              file=sys.stderr)
        sys.exit(0)

    # Rotate old report files and trim runs log if oversized
    rotate_reports()
    rotate_runs_file()

    # === UPDATE TEST CACHE ===
    # For targeted (manual) test runs, update the hash cache with results.
    # Smart runs already handle their own cache updates, so only do this for
    # manual/targeted runs to avoid double-updates.
    if run_data.get("trigger") == "manual" and run_data.get("overall_success"):
        try:
            import importlib.util
            script_dir = Path(__file__).resolve().parent
            spec = importlib.util.spec_from_file_location(
                "test_cache",
                str(script_dir / "test-cache.py"),
            )
            cache_mod = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(cache_mod)

            # Collect unique test files that passed
            passed_files = set()
            for test in run_data.get("tests", []):
                if test.get("result") == "success" and not test.get("skipped"):
                    test_file = test.get("file", "")
                    if test_file:
                        # Normalize: make relative to project root if absolute
                        if os.path.isabs(test_file):
                            try:
                                test_file = str(Path(test_file).relative_to(
                                    script_dir.parent.parent
                                ))
                            except ValueError:
                                continue
                        passed_files.add(test_file)

            if passed_files:
                cache_mod.update_cache(list(passed_files), result="pass")

            # Invalidate failed test files
            failed_files = set()
            for test in run_data.get("tests", []):
                if test.get("result") in ("failure", "error"):
                    test_file = test.get("file", "")
                    if test_file:
                        if os.path.isabs(test_file):
                            try:
                                test_file = str(Path(test_file).relative_to(
                                    script_dir.parent.parent
                                ))
                            except ValueError:
                                continue
                        failed_files.add(test_file)

            if failed_files:
                cache_mod.invalidate_tests(list(failed_files))
        except Exception:
            pass  # Silent on cache errors

    # Print summary message for Claude to see
    summary_parts = []
    if run_data["passed"]:
        summary_parts.append(f"{run_data['passed']} passed")
    if run_data["failed"]:
        summary_parts.append(f"{run_data['failed']} failed")
    if run_data["errors"]:
        summary_parts.append(f"{run_data['errors']} errors")
    if run_data["skipped"]:
        summary_parts.append(f"{run_data['skipped']} skipped")
    counts = ", ".join(summary_parts) if summary_parts else "no tests"

    duration_s = run_data["duration_ms"] / 1000
    status = "PASS" if run_data["overall_success"] else "FAIL"

    one_line = f"Test results logged: {status} ({counts}) in {duration_s:.1f}s"
    detail = one_line

    # Show failed test names if any
    if run_data["failed"] > 0 or run_data["errors"] > 0:
        failed_tests = [
            t["name"]
            for t in run_data["tests"]
            if t["result"] in ("failure", "error")
        ]
        if failed_tests:
            detail += "\nFailed:"
            for name in failed_tests[:5]:
                detail += f"\n  - {name}"
            if len(failed_tests) > 5:
                detail += f"\n  ... and {len(failed_tests) - 5} more"

    # Compress output when Context Mode is active (but always pass through failures)
    if run_data["overall_success"]:
        message = compress_output("capture-test-results", one_line, detail)
    else:
        # Failures always pass through full output — actionable information
        message = detail

    print(
        json.dumps(
            {
                "hookSpecificOutput": {
                    "hookEventName": "PostToolUse",
                    "additionalContext": message,
                }
            }
        )
    )

    sys.exit(0)


if __name__ == "__main__":
    main()
